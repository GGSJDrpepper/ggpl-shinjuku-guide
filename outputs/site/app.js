function combinedValue(...values) {
  return values.filter(Boolean).join(" / ");
}

function pairedValue(primary, secondary) {
  return `${primary || "—"} / ${secondary || "—"}`;
}

function cashGamePeriodData(event) {
  if (event?.cashGamePeriods?.[currentCashGamePeriod]) {
    const period = event.cashGamePeriods[currentCashGamePeriod];
    return {
      rates: period.rates || [],
      chipPurchase: period.chipPurchase || [],
      chipWithdrawal: period.chipWithdrawal || [],
      notice: textFor(period.notice)
    };
  }

  if (currentCashGamePeriod === "night") {
    const rates = event.nightRates || [];
    const chipPurchase = event.nightChipPurchase || [];
    const chipWithdrawal = event.nightChipWithdrawal || [];
    const hasNightData = rates.length || chipPurchase.length || chipWithdrawal.length;
    return {
      rates,
      chipPurchase,
      chipWithdrawal,
      notice: hasNightData ? "" : textFor(event.nightNotice) || t("cashGamePeriodPending")
    };
  }

  return {
    rates: event.rates || [],
    chipPurchase: event.chipPurchase || [],
    chipWithdrawal: event.chipWithdrawal || [],
    notice: ""
  };
}

